package com.example.agent.core

import java.io.File
import java.util.Locale
import java.util.concurrent.ConcurrentHashMap

/**
 * Status of a tracked deliverable artifact.
 */
enum class DeliverableStatus {
  PENDING,      // Required deliverable identified, not yet written or found on disk
  IN_PROGRESS,  // File exists on disk but is 0 bytes or currently being written
  VERIFIED,     // Exists on disk with non-zero bytes and passed structural validation
  INVALID       // Exists on disk but corrupted or failed format validation
}

/**
 * Single tracked deliverable specification and verified filesystem state.
 */
data class TrackedDeliverable(
  val path: String,                 // Relative path in workspace (e.g. "report.md" or "output/data.json")
  val name: String,                 // Simple file name
  val description: String = "",     // Origin or role (e.g. "Target Report", "Script Output")
  val required: Boolean = true,
  val status: DeliverableStatus = DeliverableStatus.PENDING,
  val sizeBytes: Long = 0L,
  val lastModified: Long = 0L,
  val validationMessage: String? = null,
  val fileType: String = "",
  val qualityScore: Int = 100,
  val sha256: String? = null
)

data class DeliverableFileMetrics(
  val lineCount: Int = 0,
  val qualityScore: Int = 100,
  val sha256: String? = null
)

/**
 * Summary report of all deliverables across the workspace.
 */
data class DeliverableReport(
  val deliverables: List<TrackedDeliverable>,
  val totalRequired: Int,
  val verifiedCount: Int,
  val pendingCount: Int,
  val invalidCount: Int,
  val progressPercent: Int,
  val allSatisfied: Boolean,
  val verifiedNames: List<String>,
  val pendingOrInvalidDetails: String
)

/**
 * Authoritative system for tracking, scanning, and verifying deliverables on disk.
 * Eliminates artificial turn limits while giving the agent continuous, explicit,
 * ground-truth feedback on what deliverables exist and what remain pending.
 */
class DeliverableTracker(
  val workspaceDir: File
) {
  val deliverablesMap = ConcurrentHashMap<String, TrackedDeliverable>()

  /**
   * Initializes tracking based on the given user task and objective.
   */
  fun initializeForTask(task: Task) {
    deliverablesMap.clear()

    // 1. Explicit expected deliverable
    if (!task.expectedArtifact.isNullOrBlank()) {
      val clean = PathSecurity.toCanonicalRelativePath(workspaceDir, task.expectedArtifact)
      if (clean.isNotBlank()) {
        registerDeliverable(
          path = clean,
          description = "Explicit Expected Deliverable",
          required = true
        )
        return
      }
    }

    // 2. Extract deliverables from user goal
    val inferred = extractDeliverablesFromText(task.goal)
    for (name in inferred) {
      val clean = PathSecurity.toCanonicalRelativePath(workspaceDir, name)
      if (clean.isNotBlank() && !deliverablesMap.containsKey(clean)) {
        registerDeliverable(
          path = clean,
          description = "Deliverable requested in objective",
          required = true
        )
      }
    }
  }

  /**
   * Registers a deliverable to track.
   */
  fun registerDeliverable(
    path: String,
    description: String = "",
    required: Boolean = true
  ): TrackedDeliverable {
    val clean = PathSecurity.toCanonicalRelativePath(workspaceDir, path)
    val name = File(clean).name
    val item = TrackedDeliverable(
      path = clean,
      name = name,
      description = description,
      required = required,
      status = DeliverableStatus.PENDING,
      fileType = determineFileType(name)
    )
    deliverablesMap[clean] = item
    return item
  }

  /**
   * Scans the workspace directory, checks existence and validation for every tracked deliverable,
   * discovers any new deliverable-quality files generated by tools, and returns the authoritative report.
   */
  fun scanAndVerify(artifactManager: ArtifactManager? = null): DeliverableReport {
    if (!workspaceDir.exists()) {
      workspaceDir.mkdirs()
    }

    // 1. Check all registered deliverables against ground-truth disk state
    for ((path, item) in deliverablesMap.entries) {
      val directFile = File(workspaceDir, path)
      val targetFile = if (directFile.exists()) {
        directFile
      } else {
        // Fallback: search recursively in workspace for a file matching name or extension
        findMatchingFile(item.name)
      }

      if (targetFile == null || !targetFile.exists() || !targetFile.isFile) {
        deliverablesMap[path] = item.copy(
          status = DeliverableStatus.PENDING,
          sizeBytes = 0L,
          validationMessage = "File does not exist on disk in \$WORKSPACE"
        )
      } else {
        val length = targetFile.length()
        val lastMod = targetFile.lastModified()
        if (length == 0L) {
          deliverablesMap[path] = item.copy(
            status = DeliverableStatus.IN_PROGRESS,
            sizeBytes = 0L,
            lastModified = lastMod,
            validationMessage = "File exists on disk but is empty (0 bytes)"
          )
        } else {
          val validation = ArtifactValidatorRegistry.validateExistingFile(targetFile)
          if (validation.isValid) {
            if (targetFile.canonicalFile != directFile.canonicalFile && !directFile.exists()) {
              try {
                directFile.parentFile?.mkdirs()
                targetFile.copyTo(directFile, overwrite = false)
              } catch (_: Exception) {}
            }
            val effectiveFile = if (directFile.exists() && directFile.length() > 0) directFile else targetFile
            val relPath = PathSecurity.toCanonicalRelativePath(workspaceDir, PathSecurity.getRelativePath(workspaceDir, effectiveFile))
            deliverablesMap[path] = item.copy(
              path = relPath,
              name = effectiveFile.name,
              status = DeliverableStatus.VERIFIED,
              sizeBytes = length,
              lastModified = lastMod,
              validationMessage = validation.detectedFormat ?: "Valid (${formatFileSize(length)})",
              fileType = determineFileType(effectiveFile.name)
            )
            // Ensure registered in ArtifactManager as well
            artifactManager?.registerArtifact(relPath)
          } else {
            deliverablesMap[path] = item.copy(
              status = DeliverableStatus.INVALID,
              sizeBytes = length,
              lastModified = lastMod,
              validationMessage = validation.errorMessage ?: "Validation failed"
            )
          }
        }
      }
    }

    // 2. Auto-discover non-temporary deliverable files created in workspace
    workspaceDir.walkTopDown()
      .onEnter { dir ->
        val dName = dir.name.lowercase(Locale.ROOT)
        !dName.startsWith(".") && dName !in INTERNAL_WORKSPACE_DIRS
      }
      .maxDepth(4)
      .filter { file ->
        val nameLower = file.name.lowercase(Locale.ROOT)
        val rel = PathSecurity.toCanonicalRelativePath(workspaceDir, PathSecurity.getRelativePath(workspaceDir, file))
        val isTemp = nameLower.startsWith(".") ||
          nameLower.startsWith(".tmp_") ||
          nameLower.startsWith("temp_") ||
          nameLower.startsWith("tmp_") ||
          nameLower.startsWith("search_") ||
          nameLower.startsWith("scrape_") ||
          nameLower.startsWith("cache_") ||
          nameLower.startsWith("query_") ||
          nameLower.startsWith("raw_") ||
          nameLower.startsWith("draft_") ||
          nameLower.endsWith(".tmp") ||
          nameLower.endsWith(".temp") ||
          nameLower.endsWith(".part") ||
          nameLower.endsWith(".bak") ||
          nameLower.endsWith(".log") ||
          isInternalWorkspacePath(rel, nameLower)
        file.isFile &&
          file.length() > 0 &&
          !isTemp
      }
      .forEach { file ->
        val rel = PathSecurity.toCanonicalRelativePath(workspaceDir, PathSecurity.getRelativePath(workspaceDir, file))
        val ext = file.extension.lowercase(Locale.ROOT)
        // High-value deliverable extensions
        if (ext in listOf("md", "docx", "xlsx", "xls", "pdf", "csv", "json", "jsonl", "html", "py", "sh", "txt")) {
          val alreadyTracked = deliverablesMap.values.any { it.name.equals(file.name, ignoreCase = true) || it.path == rel }
          if (!alreadyTracked) {
            val validation = ArtifactValidatorRegistry.validateExistingFile(file)
            val isValid = validation.isValid
            val item = TrackedDeliverable(
              path = rel,
              name = file.name,
              description = "Discovered Workspace Output",
              required = false, // Auto-discovered files enrich the deliverable set
              status = if (isValid) DeliverableStatus.VERIFIED else DeliverableStatus.INVALID,
              sizeBytes = file.length(),
              lastModified = file.lastModified(),
              validationMessage = if (isValid) (validation.detectedFormat ?: "Valid") else validation.errorMessage,
              fileType = determineFileType(file.name)
            )
            deliverablesMap[rel] = item
            artifactManager?.registerArtifact(rel)
          }
        }
      }

    val allList = deliverablesMap.values.sortedWith(
      compareByDescending<TrackedDeliverable> { it.required }
        .thenBy { it.status != DeliverableStatus.VERIFIED }
        .thenBy { it.name }
    )

    val requiredItems = allList.filter { it.required }
    val totalRequired = requiredItems.size
    val verifiedCount = requiredItems.count { it.status == DeliverableStatus.VERIFIED }
    val pendingCount = requiredItems.count { it.status == DeliverableStatus.PENDING || it.status == DeliverableStatus.IN_PROGRESS }
    val invalidCount = requiredItems.count { it.status == DeliverableStatus.INVALID }

    val progressPercent = if (totalRequired == 0) {
      if (allList.any { it.status == DeliverableStatus.VERIFIED }) 100 else 0
    } else {
      ((verifiedCount.toDouble() / totalRequired.toDouble()) * 100).toInt().coerceIn(0, 100)
    }

    val allSatisfied = if (totalRequired > 0) {
      verifiedCount == totalRequired
    } else {
      // If no explicit required files, any verified deliverable or valid workspace state satisfies
      allList.any { it.status == DeliverableStatus.VERIFIED }
    }

    val verifiedNames = allList.filter { it.status == DeliverableStatus.VERIFIED }.map { it.name }

    val pendingOrInvalidList = requiredItems.filter { it.status != DeliverableStatus.VERIFIED }
    val pendingDetails = if (pendingOrInvalidList.isEmpty()) {
      "All required deliverables verified on disk."
    } else {
      pendingOrInvalidList.joinToString("; ") {
        "${it.name} (${it.status.name}: ${it.validationMessage ?: "awaiting creation"})"
      }
    }

    return DeliverableReport(
      deliverables = allList,
      totalRequired = totalRequired,
      verifiedCount = verifiedCount,
      pendingCount = pendingCount,
      invalidCount = invalidCount,
      progressPercent = progressPercent,
      allSatisfied = allSatisfied,
      verifiedNames = verifiedNames,
      pendingOrInvalidDetails = pendingDetails
    )
  }

  /**
   * Produces authoritative prompt guidance for the LLM system context.
   * Accepts the freshly computed report when the caller already scanned this turn,
   * avoiding a duplicate full workspace scan.
   */
  fun generatePromptSummary(report: DeliverableReport? = null): String {
    val effectiveReport = report ?: scanAndVerify()
    val sb = StringBuilder()
    sb.appendLine("═══════════════════════════════════════════════════════════")
    sb.appendLine("AUTHORITATIVE DELIVERABLES TRACKER (Ground Truth on Disk)")
    sb.appendLine("═══════════════════════════════════════════════════════════")

    if (effectiveReport.deliverables.isEmpty()) {
      sb.appendLine("Status: No specific deliverable files requested yet.")
      sb.appendLine("Directive: Synthesize all required outputs to \$WORKSPACE when ready.")
      return sb.toString()
    }

    sb.appendLine("Deliverable Verification: ${effectiveReport.verifiedCount}/${effectiveReport.totalRequired.coerceAtLeast(1)} Verified (${effectiveReport.progressPercent}%)")
    for (d in effectiveReport.deliverables) {
      val statusIcon = when (d.status) {
        DeliverableStatus.VERIFIED -> "✓ [VERIFIED]"
        DeliverableStatus.IN_PROGRESS -> "⏳ [IN PROGRESS]"
        DeliverableStatus.PENDING -> "○ [PENDING]"
        DeliverableStatus.INVALID -> "✗ [INVALID]"
      }
      val reqTag = if (d.required) "(Required)" else "(Optional/Created)"
      val sizeStr = if (d.sizeBytes > 0) "${formatFileSize(d.sizeBytes)}" else "0 B"
      val details = d.validationMessage ?: ""
      sb.appendLine("• $statusIcon ${d.name} $reqTag - $sizeStr - $details")
    }

    sb.appendLine()
    if (effectiveReport.allSatisfied) {
      sb.appendLine("STATUS: All required deliverables exist on disk and are authoritatively verified!")
      sb.appendLine("DIRECTIVE: If your objective is satisfied, do not execute further exploratory tools. Return your final plain-text completion summary now.")
    } else {
      sb.appendLine("STATUS: Deliverables still pending: ${effectiveReport.pendingOrInvalidDetails}")
      sb.appendLine("DIRECTIVE: Continue working. Focus on writing and verifying the remaining deliverable files in \$WORKSPACE.")
    }
    sb.appendLine("═══════════════════════════════════════════════════════════")
    return sb.toString()
  }

  fun findMatchingFile(fileName: String): File? {
    val direct = File(workspaceDir, fileName)
    if (direct.exists() && direct.length() > 0L) return direct

    val candidateFiles = workspaceDir.walkTopDown()
      .onEnter { dir ->
        val dName = dir.name.lowercase(Locale.ROOT)
        !dName.startsWith(".") && dName !in INTERNAL_WORKSPACE_DIRS
      }
      .maxDepth(4)
      .filter { f ->
        if (!f.isFile || f.length() <= 0L) return@filter false
        val rel = PathSecurity.toCanonicalRelativePath(workspaceDir, PathSecurity.getRelativePath(workspaceDir, f))
        !isInternalWorkspacePath(rel, f.name.lowercase(Locale.ROOT))
      }
      .toList()

    // 1. Recursive exact case-insensitive match in workspace subdirectories
    val exactMatch = candidateFiles.firstOrNull {
      it.name.equals(fileName, ignoreCase = true)
    }
    if (exactMatch != null) return exactMatch

    // 2. Typo-tolerant match (Levenshtein distance <= 2 on base name with matching extension, e.g. Raport_diag.md vs Rapport_diag.md)
    val ext = fileName.substringAfterLast('.', "").lowercase(Locale.ROOT)
    val reqBase = fileName.substringBeforeLast('.').lowercase(Locale.ROOT)
    if (reqBase.length >= 4 && ext.isNotEmpty()) {
      val typoMatch = candidateFiles.firstOrNull { f ->
        f.extension.lowercase(Locale.ROOT) == ext &&
          levenshteinDistance(reqBase, f.nameWithoutExtension.lowercase(Locale.ROOT)) <= 2
      }
      if (typoMatch != null) {
        try {
          if (!direct.exists()) {
            direct.parentFile?.mkdirs()
            typoMatch.copyTo(direct, overwrite = false)
            return direct
          }
        } catch (_: Exception) {}
        return typoMatch
      }
    }

    // 3. Extension-based fuzzy match for docx/xlsx if user asked for a generic document
    if (ext in listOf("docx", "doc")) {
      return candidateFiles.firstOrNull {
        it.extension.lowercase(Locale.ROOT) in listOf("docx", "doc") && it.length() > 500
      }
    } else if (ext in listOf("xlsx", "xls")) {
      return candidateFiles.firstOrNull {
        it.extension.lowercase(Locale.ROOT) in listOf("xlsx", "xls") && it.length() > 300
      }
    }
    return null
  }

  fun extractDeliverablesFromText(text: String): Set<String> {
    val results = mutableSetOf<String>()

    // 1. Explicit deliverable filenames by extension in text (e.g. traffic_report.md, metrics.json)
    val extRegex = Regex("""\b([a-zA-Z0-9_\-./]+\.(?:md|markdown|json|jsonl|csv|xlsx|xls|docx|doc|txt|py|sh|pdf|html|yaml|yml))\b""", RegexOption.IGNORE_CASE)
    val inputKeywords = listOf("analyze", "analyzes", "analyzing", "read", "reading", "from", "inspect", "inspecting", "process", "processing", "parse", "parsing", "using", "load", "loading")
    extRegex.findAll(text).forEach { match ->
      val candidate = match.groupValues[1].trim()
      val name = File(candidate).name
      val lower = name.lowercase(Locale.ROOT)
      val matchIndex = match.range.first
      val preceding = if (matchIndex > 0) text.substring(0, matchIndex).takeLast(25).lowercase(Locale.ROOT) else ""
      val isInput = inputKeywords.any { preceding.contains(it) }

      if (!isInput && !lower.endsWith(".com") && !lower.endsWith(".org") && !lower.endsWith(".net") &&
          lower !in listOf("index.html", "script.sh", "example.com", "scribd.com", "google.com")
      ) {
        results.add(name)
      }
    }

    // 2. Action phrases (e.g. "write results to report", "save findings in audit_doc")
    val actionRegexes = listOf(
      Regex("""(?:record|write|save|output|produce|generate|create|build)\s+(?:findings|results|report|audit|document|summary|data|dataset)?\s*(?:to|in|into)?\s*[`"']?([a-zA-Z0-9_\-./]+\.[a-zA-Z0-9]{2,4})[`"']?""", RegexOption.IGNORE_CASE),
      Regex("""(?:deliverable|artifact|report|file):\s*[`"']?([a-zA-Z0-9_\-./]+\.[a-zA-Z0-9]{2,4})[`"']?""", RegexOption.IGNORE_CASE)
    )

    for (regex in actionRegexes) {
      regex.findAll(text).forEach { match ->
        val candidate = match.groupValues[1].trim()
        val name = File(candidate).name
        if (name !in listOf("scribd.com", "example.com", "google.com", "github.com", "index.html", "script.sh")) {
          results.add(name)
        }
      }
    }

    val lowerText = text.lowercase(Locale.ROOT)
    if ((lowerText.contains("word file") || lowerText.contains("wordfile") || lowerText.contains("word doc") || lowerText.contains("word document") || lowerText.contains(".docx")) && results.none { it.endsWith(".docx") }) {
      results.add("document.docx")
    }
    if ((lowerText.contains("excel") || lowerText.contains("spreadsheet") || lowerText.contains("xlsx")) && results.none { it.endsWith(".xlsx") || it.endsWith(".xls") }) {
      results.add("spreadsheet.xlsx")
    }
    if ((lowerText.contains("pdf file") || lowerText.contains("pdf document") || lowerText.contains(".pdf")) && results.none { it.endsWith(".pdf") }) {
      results.add("document.pdf")
    }
    if ((lowerText.contains("audit report") || lowerText.contains("research report") || lowerText.contains("summary report")) && results.none { it.endsWith(".md") || it.endsWith(".docx") || it.endsWith(".pdf") }) {
      results.add("report.md")
    }

    return results
  }

  fun determineFileType(fileName: String): String {
    val ext = fileName.substringAfterLast('.', "").lowercase()
    return when (ext) {
      "md", "markdown" -> "Markdown Document"
      "docx", "doc" -> "Word Document"
      "xlsx", "xls" -> "Excel Spreadsheet"
      "json" -> "JSON Document"
      "jsonl" -> "JSON Lines"
      "csv" -> "CSV Spreadsheet"
      "py" -> "Python Script"
      "sh" -> "Shell Script"
      "txt" -> "Text Document"
      "html", "htm" -> "HTML Webpage"
      "pdf" -> "PDF Document"
      "png", "jpg", "jpeg", "webp" -> "Image"
      else -> "Deliverable File"
    }
  }

  companion object {
    val INTERNAL_WORKSPACE_DIRS = setOf(
      "notes", "documents", "tmp", "temp", "cache", "logs", "bin", "lib",
      "venv", ".venv", "node_modules", "__pycache__", "build",
      ".git", ".sessions", ".scratchpad", ".observations", ".artifacts", ".mcp_data", ".exec"
    )

    val INTERNAL_WORKSPACE_FILES = setOf(
      "data.db", "data.db-wal", "data.db-shm", "data.db-journal",
      "task_history.jsonl", "checkpoint.json", "research.jsonl", "mcp_servers.json",
      "aragon_exec_script.py", ".sudo_as_admin_successful", ".bashrc", ".bash_logout", ".profile"
    )

    /**
     * Authoritatively determines if a relative workspace path or file name belongs to internal
     * agent state, session checkpoints, scratchpad logs, or system databases rather than user files/deliverables.
     */
    fun isInternalWorkspacePath(relPath: String, fileNameLower: String = File(relPath).name.lowercase(Locale.ROOT)): Boolean {
      if (fileNameLower.isBlank() || fileNameLower.startsWith(".")) return true
      if (fileNameLower in INTERNAL_WORKSPACE_FILES) return true
      if (fileNameLower.endsWith(".db-journal") || fileNameLower.endsWith(".db-wal") || fileNameLower.endsWith(".db-shm")) return true
      if (fileNameLower.startsWith("session_") && fileNameLower.endsWith(".json")) return true
      if (Regex("^task_[0-9a-f]{8}\\.json$").matches(fileNameLower)) return true

      val normalized = relPath.trim().replace('\\', '/').trimStart('/')
      val segments = normalized.split('/').filter { it.isNotBlank() }
      for (i in 0 until (segments.size - 1).coerceAtLeast(0)) {
        val seg = segments[i].lowercase(Locale.ROOT)
        if (seg.startsWith(".") || seg in INTERNAL_WORKSPACE_DIRS) {
          return true
        }
      }
      if (segments.size == 1 && segments[0].lowercase(Locale.ROOT) in INTERNAL_WORKSPACE_DIRS) {
        return true
      }
      return false
    }

    fun levenshteinDistance(a: String, b: String): Int {
      if (a == b) return 0
      if (a.isEmpty()) return b.length
      if (b.isEmpty()) return a.length
      val prev = IntArray(b.length + 1) { it }
      val curr = IntArray(b.length + 1)
      for (i in 1..a.length) {
        curr[0] = i
        for (j in 1..b.length) {
          val cost = if (a[i - 1] == b[j - 1]) 0 else 1
          curr[j] = minOf(
            curr[j - 1] + 1,
            prev[j] + 1,
            prev[j - 1] + cost
          )
        }
        System.arraycopy(curr, 0, prev, 0, b.length + 1)
      }
      return prev[b.length]
    }

    fun formatFileSize(bytes: Long): String {
      return when {
        bytes < 1024 -> "$bytes B"
        bytes < 1024 * 1024 -> "${bytes / 1024} KB"
        else -> "${String.format(Locale.US, "%.1f", bytes / (1024.0 * 1024.0))} MB"
      }
    }

    fun computeDeliverableMetrics(file: File): DeliverableFileMetrics {
      if (!file.exists() || !file.isFile) return DeliverableFileMetrics()
      val lines = try {
        if (file.length() < 5_000_000) {
          file.bufferedReader().useLines { linesSeq -> linesSeq.count() }
        } else 0
      } catch (_: Exception) { 0 }
      val sha = try {
        val digest = java.security.MessageDigest.getInstance("SHA-256")
        file.inputStream().use { input ->
          val buf = ByteArray(8192)
          var len = input.read(buf)
          while (len != -1) {
            digest.update(buf, 0, len)
            len = input.read(buf)
          }
        }
        digest.digest().joinToString("") { "%02x".format(it) }
      } catch (_: Exception) { null }
      return DeliverableFileMetrics(
        lineCount = lines,
        qualityScore = if (lines > 0 || file.length() > 0) 100 else 0,
        sha256 = sha
      )
    }
  }
}
